    var current = localStorage.getItem('lang') || 'en';

    function apply() {
        document.documentElement.setAttribute('lang', current);
        var dict = translations[current] || {};
        document.querySelectorAll('[data-i18n]').forEach(function (el) {
            var t = dict[el.getAttribute('data-i18n')];
            if (t !== undefined) el.textContent = t;
        });
        document.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) {
            var t = dict[el.getAttribute('data-i18n-placeholder')];
            if (t !== undefined) el.setAttribute('placeholder', t);
        });
        document.querySelectorAll('.lang-btn').forEach(function (btn) {
            btn.classList.toggle('active', btn.getAttribute('data-lang') === current);
        });
    }

    function setLang(lang) {
        if (!translations[lang]) return;
        current = lang;
        localStorage.setItem('lang', lang);
        apply();
    }

    document.addEventListener('DOMContentLoaded', function () {
        document.querySelectorAll('.lang-btn').forEach(function (btn) {
            btn.addEventListener('click', function () {
                setLang(btn.getAttribute('data-lang'));
            });
        });
        apply();
    });
